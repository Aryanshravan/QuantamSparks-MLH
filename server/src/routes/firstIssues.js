import express from 'express';
import { githubService } from '../services/githubService.js';
import { gemmaService } from '../services/gemmaService.js';

const router = express.Router();

router.post('/', async (req, res, next) => {
  try {
    const { repoUrl } = req.body;
    if (!repoUrl) {
      return res.status(400).json({ error: 'Repository URL is required.' });
    }

    const { owner, repo, fullName } = githubService.parseRepoUrl(repoUrl);

    console.log(`[FirstIssues] Fetching source files for ${fullName}...`);
    const metadata = await githubService.getRepoMetadata(owner, repo);
    const tree = await githubService.getRepoTree(owner, repo, metadata.defaultBranch);
    const manifests = await githubService.getManifests(owner, repo, metadata.defaultBranch);
    
    // Retrieve up to 4 representative code files to inspect actual implementation
    const sourceFiles = await githubService.getRepresentativeSourceFiles(owner, repo, tree, metadata.defaultBranch, 4);

    if (sourceFiles.length === 0) {
      return res.status(400).json({
        error: 'No inspectable source files (.js, .ts, .py, .go, .rs, etc.) found in the repository.'
      });
    }

    const sourceContext = sourceFiles
      .map(sf => `### FILE: ${sf.path} ###\n\`\`\`\n${sf.content.slice(0, 2500)}\n\`\`\``)
      .join('\n\n');

    const systemPrompt = `You are IssuePilot AI, an expert code analyzer powered by Google Gemma.
Your job is to discover 3 to 4 high-quality, beginner-friendly contribution opportunities by inspecting real source code from a GitHub repository.

Focus on:
1. Missing or unhandled edge cases / input validation
2. Missing unit tests for critical functions
3. Incomplete error handling or uncaught exceptions
4. Documentation or docstring gaps in complex logic
5. Duplicated code or small refactoring suitable for a newcomer

STRICT ACCURACY RULES:
- ONLY reference files and code snippets that ACTUALLY exist in the provided source code below.
- Do NOT invent fake bugs or imaginary functions.
- Clearly differentiate between verified observations (e.g. "function X has no null check") and hypotheses.
- Provide step-by-step guidance suitable for a beginner.

Return your analysis as a valid JSON object with the following structure:
{
  "summary": "Brief 1-2 sentence overview of the code quality and testability.",
  "issues": [
    {
      "id": "ISSUE-1",
      "title": "Clear actionable task title",
      "category": "Edge Cases" | "Testing" | "Error Handling" | "Documentation" | "Maintainability",
      "filePath": "Exact file path from code",
      "evidenceSnippet": "Short exact code snippet or location from the provided file",
      "reason": "Why this change is beneficial to the project",
      "difficulty": "Beginner" | "Easy-Intermediate",
      "difficultyReason": "Why this is accessible to a newcomer",
      "implementationSteps": [
        "Step 1...",
        "Step 2..."
      ],
      "suggestedTests": [
        "Test description 1..."
      ]
    }
  ]
}

Ensure you output strictly JSON without markdown backticks around the json, or standard markdown json block.`;

    const userPrompt = `REPOSITORY: ${fullName} (${metadata.language})
FILES ANALYZED: ${sourceFiles.map(f => f.path).join(', ')}

REAL SOURCE CODE SAMPLES:
${sourceContext}

Analyze the code and produce the 3-4 grounded first-issue opportunities in JSON format now:`;

    console.log(`[FirstIssues] Generating issues with Google Gemma for ${fullName}...`);
    const gemmaResult = await gemmaService.chatCompletion([
      { role: 'system', content: systemPrompt },
      { role: 'user', content: userPrompt }
    ], { temperature: 0.2, max_tokens: 2500 });

    let parsed = null;
    try {
      // Clean up markdown block if Gemma outputs ```json ... ```
      let clean = gemmaResult.content.trim();
      if (clean.startsWith('```json')) {
        clean = clean.replace(/^```json\s*/, '').replace(/\s*```$/, '');
      } else if (clean.startsWith('```')) {
        clean = clean.replace(/^```\s*/, '').replace(/\s*```$/, '');
      }
      parsed = JSON.parse(clean);
    } catch {
      // If direct JSON parsing fails, wrap in fallback structure
      parsed = {
        summary: "Grounded code analysis generated by Google Gemma.",
        rawOutput: gemmaResult.content,
        issues: []
      };
    }

    res.json({
      repository: metadata,
      modelUsed: gemmaResult.model,
      analyzedFiles: sourceFiles.map(f => f.path),
      data: parsed
    });
  } catch (err) {
    next(err);
  }
});

export default router;
